static ULONGLONG unix_now(void)
{
    FILETIME ft;
    ULARGE_INTEGER u;

    GetSystemTimeAsFileTime(&ft);
    u.LowPart = ft.dwLowDateTime;
    u.HighPart = ft.dwHighDateTime;
    if (u.QuadPart < 116444736000000000ull)
        return 0;
    return (u.QuadPart - 116444736000000000ull) / 10000000ull;
}

/* A version string from the (verified) manifest is plain ASCII. */
static void version_w(const char *v, wchar_t *out, size_t cap)
{
    size_t i;
    for (i = 0; v[i] != 0 && i + 1 < cap; i++)
        out[i] = (wchar_t)(unsigned char)v[i];
    out[i] = 0;
}

static void open_notes(const kb_update_manifest *m)
{
    wchar_t url[KB_UPD_URL_MAX + 1];

    /* notes-url was checked against the repo's https://github.com/... prefix. */
    if (MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, m->notes_url, -1, url,
                            (int)ARRAYSIZE(url)) <= 0)
        return;
    if ((INT_PTR)ShellExecuteW(NULL, L"open", url, NULL, NULL, SW_SHOWNORMAL) <= 32)
        MessageBoxW(NULL, L"KeyBridge couldn't open your web browser.", KB_APP_NAME,
                    MB_OK | MB_ICONWARNING | MB_SETFOREGROUND);
}

static void pending_clear(void)
{
    if (g_upd_pending != NULL) {
        HeapFree(GetProcessHeap(), 0, g_upd_pending);
        g_upd_pending = NULL;
    }
}

static void pending_set(const kb_update_manifest *m)
{
    if (g_upd_pending == NULL)
        g_upd_pending = (kb_update_manifest *)HeapAlloc(GetProcessHeap(), 0, sizeof(*g_upd_pending));
    if (g_upd_pending != NULL)
        *g_upd_pending = *m;
}

/* The part after "Couldn't check for updates: " / "Couldn't download the update: ". */
static void update_error_text(kb_upd_result r, DWORD detail, wchar_t *buf, size_t cap)
{
    switch (r) {
    case KB_UPD_ERR_NETWORK:
        if (detail == ERROR_WINHTTP_SECURE_FAILURE)
            (void)StringCchCopyW(buf, cap, L"the secure connection to GitHub couldn't be verified.");
        else if (detail == ERROR_WINHTTP_TIMEOUT)
            (void)StringCchCopyW(buf, cap, L"the connection to GitHub timed out.");
        else
            (void)StringCchCopyW(buf, cap, L"KeyBridge can't reach GitHub. Check your internet connection.");
        break;
    case KB_UPD_ERR_HTTP:
        (void)StringCchPrintfW(buf, cap, L"GitHub answered with error %lu.", detail);
        break;
    case KB_UPD_ERR_TOO_LARGE:
    case KB_UPD_ERR_INVALID:
        (void)StringCchCopyW(buf, cap, L"the update information isn't validly signed.");
        break;
    case KB_UPD_ERR_FILE:
        (void)StringCchPrintfW(buf, cap, L"KeyBridge couldn't save the download on this PC (error %lu).",
                               detail);
        break;
    default:
        (void)StringCchCopyW(buf, cap, L"something went wrong on this PC.");
        break;
    }
}

